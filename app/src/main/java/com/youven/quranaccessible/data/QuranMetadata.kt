    fun surah(number: Int): SurahInfo = SURAHS.getOrElse(number - 1) { SURAHS[0] }

    fun surahForPage(page: Int): SurahInfo {
        val clamped = page.coerceIn(1, 604)
        for (i in SURAHS.indices.reversed()) {
            if (SURAHS[i].startPage <= clamped) return SURAHS[i]
        }
        return SURAHS[0]
    }

    fun juzForPage(page: Int): Int {
        val clamped = page.coerceIn(1, 604)
        for (i in JUZS.indices.reversed()) {
            if (JUZS[i].startPage <= clamped) return JUZS[i].number
        }
        return 1
    }

    fun rubForPage(page: Int): RubInfo {
        val clamped = page.coerceIn(1, 604)
        for (i in RUBS.indices.reversed()) {
            if (RUBS[i].pageNumber <= clamped) return RUBS[i]
        }
        return RUBS[0]
    }

    fun toArabicDigits(number: Int): String {
        val eastern = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')
        return number.toString().map { c -> if (c in '0'..'9') eastern[c - '0'] else c }.joinToString("")
    }
