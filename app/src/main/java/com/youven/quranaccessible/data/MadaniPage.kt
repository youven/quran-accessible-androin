package com.youven.quranaccessible.data

data class PageSpec(val firstVerse: String, val lastVerse: String, val wordCount: Int) {
    val minChapter: Int get() = firstVerse.substringBefore(':').toInt()
    val maxChapter: Int get() = lastVerse.substringBefore(':').toInt()
    val chapters: List<Int> get() = (minChapter..maxChapter).toList()
}

/** Madani 1421H, QCF V2: never mix page fonts or editions. */
object MadaniPage {
    const val COUNT = 604
    const val EDITION = "qcf-v2-mushaf-1"

    fun fontUrl(page: Int): String {
        require(page in 1..COUNT)
        return "https://verses.quran.foundation/fonts/quran/hafs/v2/ttf/p$page.ttf"
    }

    fun restoredPage(value: Int): Int = value.coerceIn(1, COUNT)

    /** Accept Arabic, Persian and ASCII decimal digits without accepting signs or decimals. */
    fun parse(input: String): Int? {
        val trimmed = input.trim()
        if (trimmed.isEmpty() || trimmed.length > 3) return null
        val digits = trimmed.map { it.digitToIntOrNull() ?: return null }.joinToString("")
        return digits.toIntOrNull()?.takeIf { it in 1..COUNT }
    }

    fun spec(page: Int): PageSpec {
        require(page in 1..COUNT)
        val offset = (page - 1) * 5
        val fCh = SPECS[offset].toInt()
        val fV = SPECS[offset + 1].toInt()
        val lCh = SPECS[offset + 2].toInt()
        val lV = SPECS[offset + 3].toInt()
        val words = SPECS[offset + 4].toInt()
        return PageSpec("$fCh:$fV", "$lCh:$lV", words)
    }

    /** Finds the Quran page (1..604) that contains the specified chapter and verse number. */
    fun pageForVerse(chapter: Int, verse: Int): Int {
        for (p in 1..COUNT) {
            val offset = (p - 1) * 5
            val fCh = SPECS[offset].toInt()
            val fV = SPECS[offset + 1].toInt()
            val lCh = SPECS[offset + 2].toInt()
            val lV = SPECS[offset + 3].toInt()
            if (chapter in fCh..lCh) {
                val afterStart = if (chapter == fCh) verse >= fV else true
                val beforeEnd = if (chapter == lCh) verse <= lV else true
                if (afterStart && beforeEnd) return p
            }
        }
        return 1
    }

